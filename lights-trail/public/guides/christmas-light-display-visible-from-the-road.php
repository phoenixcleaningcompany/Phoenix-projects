<p>The commonest mistake with a home Christmas display is not a lack of lights.
It is that the whole thing gets designed from a stepladder, at arm's length, in
daylight. The people who will actually see it are standing on the pavement
twenty feet away, at night, probably in the rain, for about ninety seconds.</p>

<p>Everything below follows from that one difference.</p>

<h2>Go and stand where they will stand</h2>
<p>Before you buy anything, go out to the pavement after dark and look at your
house. Where does the eye land first? What is already lit — a porch light, a
window, a street lamp — and what is that doing to everything around it? A
display competing with a security light will lose every time.</p>

<h2>Pick one shape and commit to it</h2>
<p>From a distance you do not read detail, you read silhouette. A clean outline
of the roofline, one strongly lit tree, a single glowing window — any of these
carries further than lights scattered evenly across the whole frontage. Even
coverage is the enemy: it flattens the house into a vague bright smudge.</p>

<h2>Warm white and cool white are not interchangeable</h2>
<p>Cool white reads as blue at distance, especially against wet stone or slate,
and it makes brick and render look cold and slightly clinical. Warm white sits
better on most Welsh housing stock. If you mix them, do it deliberately —
cool white for anything meant to read as ice or snow, warm for everything else.
Mixing them by accident, because two sets came from different shops, is the most
common reason a display looks cheaper than it is.</p>

<h2>Movement: less than you think</h2>
<p>One moving element in an otherwise still display draws the eye hard. Five
moving elements cancel each other out and produce visual noise. If you are
running chase or twinkle effects, slow them down further than feels right — what
looks sedate up close reads as frantic from the road.</p>

<h2>The dark parts are doing work</h2>
<p>Contrast is what makes lights look bright, and contrast needs unlit space.
A house with a lit outline and a dark middle looks far more striking than one
lit from gutter to ground. Resist filling the gaps.</p>

<h2>Think about the people who live opposite</h2>
<p>Your display is in someone else's bedroom window for several weeks. Angle
anything strong downwards or towards your own house, avoid pointing flashing
elements across the road, and consider a timer that takes everything off well
before midnight. On a trail night this matters less; through all of December it
matters a great deal.</p>

<h2>The electrics, briefly and seriously</h2>
<p>Outdoor lights must be rated for outdoor use — look for an IP rating, and
treat anything unmarked as indoor-only regardless of what the box implies.
Anything outside should run through an RCD. Keep connections off the ground and
out of standing water, and do not chain more sets together than the maker says,
whatever the plug situation tempts you into. If you are running a substantial
display, an electrician looking at it once is cheap.</p>

<h2>Finally: photograph it</h2>
<p>Take a phone photo from the pavement. The camera flattens and exposes
differently from your eye, and it is unnervingly good at showing you which bits
are working and which are mush. Most people rearrange something after seeing
that photo.</p>
